    func testHTTPChallengeMatchesRustFramingVector() throws {
        let bytes = try RelayHTTPChallenge.message(deviceID: "mac-1", method: "POST", target: "/v1/work?after=2",
                                                    epoch: Data(repeating: 7, count: 16), body: Data("payload".utf8),
